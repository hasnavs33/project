package basics1;

public class Area {

	public static void main(String[] args) {
		int a=10;
		int b=20;
		int l=30;
		int r=2;
		int h=6;
		double c;
		c=a*a;
		System.out.println(c);//area of square
		c=l*b;
		System.out.println(c);//area of rectangle
		c=3.14*r*r;
		System.out.println(c);//area of circle
		c=.5*b*h;
		System.out.println(c);//area of triangle	
	}
}
